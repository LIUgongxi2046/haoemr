const specialtyScopeByPrefix: Readonly<Record<string, string>> = Object.freeze({
  dental: 'DENTAL', dermatology: 'DERMATOLOGY', ent: 'ENT', mental: 'MENTAL_HEALTH',
  neonatal: 'NEONATAL', obgyn: 'OBGYN', ophthalmology: 'OPHTHALMOLOGY',
  pediatrics: 'PEDIATRICS', reproductive: 'REPRODUCTIVE_MEDICINE', tcm: 'TCM',
});

export const specialtyGuardRouteIds: ReadonlySet<string> = new Set(routeRegistry
  .map((route) => route.route_id)
  .filter((routeId) => routeId === 'specialty-center' || Object.keys(specialtyScopeByPrefix).some((prefix) => routeId.startsWith(`${prefix}-`))));

export function specialtyScopeForRoute(routeId: string): string | null {
  if (routeId === 'specialty-center') return null;
  const prefix = routeId.split('-', 1)[0];
  return specialtyScopeByPrefix[prefix] ?? null;
}

export type PrimaryNavigationId = 'outpatient' | 'inpatient' | 'emergency' | 'record' | 'quality' | 'data' | 'configuration';

export function primaryNavigationId(routeId: string): PrimaryNavigationId {
  const definition = routeById.get(routeId);
  if (definition?.primary_domain === 'RECORD') return 'record';
  if (definition?.primary_domain === 'QUALITY') return 'quality';
  if (definition?.primary_domain === 'DATA' || definition?.primary_domain === 'COLLABORATION') return 'data';
  if (['AI', 'CONFIG', 'ADMIN'].includes(definition?.primary_domain ?? '')) return 'configuration';
  if (/^(inpatient|ip-|admission|ward)/.test(routeId)) return 'inpatient';
  if (/^(emergency|er-)/.test(routeId)) return 'emergency';
  return 'outpatient';
}
